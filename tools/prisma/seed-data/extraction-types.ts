/**
 * Commercial-contract extraction types (config-as-data, docs/07 §3). Ported
 * from the reference `DOCUMENT_TYPE_CONFIGS` catalog: each type + every field.
 * Seeded as SYSTEM TEMPLATES (`ownerOrgId = null`) by `seed.ts`, then editable
 * in the admin portal (/admin/intelligence). These are READ-ONLY extraction
 * types (no drafting `documentTypeKey`) — they are classified + extracted +
 * reviewed, not converted to a draftable document.
 *
 * Mapping from the reference shape: field `name`→`key`, `description`→`label`.
 * Every reference field was `required: true`, so `f()` defaults required=true.
 */

export type SeedFieldType =
  | 'string'
  | 'number'
  | 'currency'
  | 'date'
  | 'boolean'
  | 'enum'
  | 'table';

export interface SeedExtractionField {
  key: string;
  label: string;
  type: SeedFieldType;
  required?: boolean;
  format?: string;
  example?: string;
}

export interface SeedExtractionType {
  key: string;
  name: string;
  description: string;
  fields: SeedExtractionField[];
}

